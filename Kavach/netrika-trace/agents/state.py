"""LangGraph AgentState type definition for the Netrika-Trace pipeline."""

from typing import TypedDict


class AgentState(TypedDict):
    """Typed state schema for the LangGraph multi-agent pipeline.

    Flows through: sniffer_node → forensic_node → decision_node →
                   intervention_node (conditional) → logger_node
    """

    # Intercepted prompt text extracted from the HTTP request
    payload: str

    # HTTP metadata from the intercepted request
    user_ip: str
    target_host: str
    target_url: str
    http_method: str
    payload_size_bytes: int

    # Computed risk score (0-100) by the forensic agent
    risk_score: int

    # Individual component scores (0.0 - 1.0)
    pii_score: float
    entity_score: float
    semantic_score: float

    # List of detected entities with type, count, and position
    # Format: [{"type": "AADHAAR", "value": "****", "start": 12, "count": 1}]
    entities_found: list[dict]

    # Intent classification label
    # One of: "PII_LEAK" | "IP_LEAK" | "SAFE" | "AMBIGUOUS"
    intent_label: str

    # Decision made by the decision node
    # One of: "ALLOW" | "WARN" | "BLOCK"
    decision: str

    # Whether source code was detected in the payload
    code_detected: bool

    # Whether secrets (API keys, JWTs, etc.) were detected
    secrets_detected: bool

    # Recent messages of the same conversation (memory only, never persisted) so a secret
    # split across turns can be caught.
    scan_history: list

    # Layered scanner outcome: ALLOW | WARN | TOKENIZE | REDACT | BLOCK, plus a metadata-only summary.
    scanner_action: str
    scanner_summary: dict

    # HTML content of the breach simulation generated by Phi-3
    simulation_html: str

    # Unique incident UUID for logging and tracking
    incident_id: str

    # SHA-256 hash of the payload (for deduplication, NOT storage)
    payload_hash: str

    # First N chars of the payload for preview (capped at 200)
    payload_preview: str
