// Builds everything derived from the brand SVGs in ../logo (the originals are never modified):
//   src/components/brand/logoData.ts   inline SVG markup used by <Logo />
//   public/brand/*                     favicon, apple-touch, PWA icons, copies of the brand files
//   public/og.png                      1200x630 social card
//   ../docs/assets/*                   files referenced by the README
// Run: npm run brand
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { Resvg } from '@resvg/resvg-js'

const root = new URL('../../', import.meta.url)
const logoDir = new URL('logo/', root)
const pub = new URL('../public/', import.meta.url)
const brand = new URL('brand/', pub)
const docsAssets = new URL('docs/assets/', root)
mkdirSync(brand, { recursive: true })
mkdirSync(docsAssets, { recursive: true })

const read = (name) => readFileSync(new URL(name, logoDir), 'utf8')
const strip = (svg) => svg.replace(/<metadata>[\s\S]*?<\/metadata>/g, '')
const inner = (svg) =>
  strip(svg)
    .replace(/<title>[\s\S]*?<\/title>/, '')
    .replace(/<style>[\s\S]*?<\/style>/, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .trim()

/** Shield markup with ids replaced by a placeholder prefix and classes namespaced. */
function markBody(svg) {
  let body = inner(svg)
  const ids = [...body.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1])
  for (const id of ids) {
    const name = id.slice(1) // first letter is the file's own prefix (m / s)
    body = body.replaceAll(`id="${id}"`, `id="@@-${name}"`).replaceAll(`url(#${id})`, `url(#@@-${name})`)
  }
  return body.replace(/class="([^"]+)"/g, (_, c) => `class="${c.split(' ').map((x) => `kv-${x}`).join(' ')}"`)
}

const mark = markBody(read('kavach-mark.svg'))
const markStatic = markBody(read('kavach-mark-static.svg'))

const textPaths = [...inner(read('kavach-logo-static.svg')).matchAll(/<path d="([^"]+)" fill="(#[0-9A-Fa-f]{6})"\/>/g)]
const word = textPaths.find((m) => m[2].toUpperCase() === '#111827')?.[1]
const tagline = textPaths.find((m) => m[2].toUpperCase() === '#6B7280')?.[1]
if (!word || !tagline) throw new Error('could not find the wordmark/tagline paths in kavach-logo-static.svg')

const ts = `// GENERATED by scripts/make-brand.mjs from /logo. Do not edit by hand.
export const MARK_VIEWBOX = '-8 -8 272 272'
export const LOCKUP_VIEWBOX = '-8 -4 980 260'
export const MARK_BODY = ${JSON.stringify(mark)}
export const MARK_BODY_STATIC = ${JSON.stringify(markStatic)}
export const WORDMARK_PATH = ${JSON.stringify(word)}
export const TAGLINE_PATH = ${JSON.stringify(tagline)}
`
mkdirSync(new URL('../src/components/brand/', import.meta.url), { recursive: true })
writeFileSync(new URL('../src/components/brand/logoData.ts', import.meta.url), ts)

// ---- public copies (unmodified) ---------------------------------------------------------
for (const f of ['kavach-logo.svg', 'kavach-logo-dark.svg', 'kavach-logo-static.svg', 'kavach-mark.svg', 'kavach-mark-static.svg', 'kavach-mark-512.png', 'favicon-64.png']) {
  copyFileSync(new URL(f, logoDir), new URL(f, brand))
}
copyFileSync(new URL('kavach-mark-static.svg', logoDir), new URL('favicon.svg', pub))
copyFileSync(new URL('favicon-64.png', logoDir), new URL('favicon-64.png', pub))
for (const f of ['kavach-logo.svg', 'kavach-logo-dark.svg', 'kavach-logo-static.svg', 'kavach-mark-static.svg']) {
  copyFileSync(new URL(f, logoDir), new URL(f, docsAssets))
}

// ---- icons ------------------------------------------------------------------------------
const staticMark = strip(read('kavach-mark-static.svg'))
const png = (svg, size, opts = {}) => new Resvg(svg, { fitTo: { mode: 'width', value: size }, ...opts }).render().asPng()
const padded = (size, bg, pad) => `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 100 100">
  ${bg ? `<rect width="100" height="100" fill="${bg}"/>` : ''}
  <svg x="${pad}" y="${pad}" width="${100 - pad * 2}" height="${100 - pad * 2}" viewBox="-8 -8 272 272">${inner(staticMark)}</svg>
</svg>`
writeFileSync(new URL('apple-touch-icon.png', pub), png(padded(180, '#F6F7FB', 10), 180))
writeFileSync(new URL('icon-192.png', brand), png(staticMark, 192))
writeFileSync(new URL('icon-512.png', brand), png(staticMark, 512))
writeFileSync(new URL('icon-maskable-512.png', brand), png(padded(512, '#F6F7FB', 16), 512))

// ---- social card ------------------------------------------------------------------------
const lockup = strip(read('kavach-logo-static.svg'))
const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <defs>
    <radialGradient id="ob" cx="50%" cy="50%" r="50%"><stop offset="0" stop-color="#93C5FD" stop-opacity=".9"/><stop offset="1" stop-color="#93C5FD" stop-opacity="0"/></radialGradient>
    <radialGradient id="op" cx="50%" cy="50%" r="50%"><stop offset="0" stop-color="#F9A8D4" stop-opacity=".9"/><stop offset="1" stop-color="#F9A8D4" stop-opacity="0"/></radialGradient>
    <radialGradient id="om" cx="50%" cy="50%" r="50%"><stop offset="0" stop-color="#6EE7B7" stop-opacity=".85"/><stop offset="1" stop-color="#6EE7B7" stop-opacity="0"/></radialGradient>
  </defs>
  <rect width="1200" height="630" fill="#F6F7FB"/>
  <circle cx="160" cy="80" r="420" fill="url(#ob)"/>
  <circle cx="1040" cy="140" r="400" fill="url(#op)"/>
  <circle cx="620" cy="640" r="380" fill="url(#om)"/>
  <svg x="110" y="185" width="980" height="260" viewBox="-8 -4 980 260">${inner(lockup)}</svg>
</svg>`
writeFileSync(new URL('og.svg', pub), og)
writeFileSync(new URL('og.png', pub), png(og, 1200, { font: { loadSystemFonts: true } }))
console.log('brand assets written')
